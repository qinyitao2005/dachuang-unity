using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using Object=UnityEngine.Object;

namespace RoboticsLab.Editor
{
    public static class LabTrajectoryProgramValidation
    {
        static IEnumerator<int> routine;
        static List<string> report;
        [MenuItem("Robot Lab/Diagnostics/Validate Trajectory Programs")]
        public static void Run()
        {
            if(!EditorApplication.isPlaying)throw new InvalidOperationException("Play Mode is required.");
            if(routine!=null)throw new InvalidOperationException("Trajectory validation is already running.");
            report=new List<string>{"Trajectory program validation / "+DateTime.UtcNow.ToString("O"),
                "Parser/persistence and live robot adapter checks. Movement is generated by the runtime program Update through MoveTool; no test writes the target transform.",
                "This isolated adapter test does not bypass or validate the user-facing learning/quiz gates."};
            routine=Checks();EditorApplication.update-=Tick;EditorApplication.update+=Tick;
        }
        static void Tick()
        {
            try
            {
                if(!EditorApplication.isPlaying)throw new InvalidOperationException("Play Mode stopped before trajectory validation completed.");
                if(routine!=null&&routine.MoveNext())return;
            }
            catch(Exception e){report.Add("FAIL: "+e);Debug.LogException(e);}
            EditorApplication.update-=Tick;if(routine!=null)routine.Dispose();routine=null;
            Directory.CreateDirectory("Documentation");File.WriteAllLines("Documentation/TrajectoryProgramValidation.txt",report,new UTF8Encoding(false));
            Debug.Log("ROBOT_TRAJECTORY_PROGRAM_VALIDATION_FINISHED "+string.Join(" | ",report.Where(s=>s.StartsWith("PASS")||s.StartsWith("FAIL"))));
        }
        static IEnumerator<int> Checks()
        {
            List<LabTrajectoryStep> parsed;string error;
            Check(LabTrajectoryParser.TryParse("# comment\nSPEED 50\nMOVE 10 -20 30\nPEN DOWN\nWAIT 0.5\n",Vector3.zero,out parsed,out error)
                &&parsed.Count==4&&Vector3.Distance(parsed[1].localPosition,new Vector3(.01f,-.02f,.03f))<.000001f,"Valid language uses millimetres and preserves ordered commands");
            foreach(string invalid in new[]{"SPEED 0","SPEED 101","MOVE NaN 0 0","MOVE 0 Infinity 0","PEN MAYBE","WAIT -1","WAIT 61","System.IO.File.Delete(\"x\")","MOVE 1 2 3 SPEED 50 SPEED 60"})
            {
                Check(!LabTrajectoryParser.TryParse("# first line\n"+invalid,Vector3.zero,out parsed,out error)&&error.Contains("2"),"Invalid line rejected with source line: "+invalid);
            }
            Check(!LabTrajectoryParser.TryParse(new string('x',LabTrajectoryProgram.MaximumTextLength+1),Vector3.zero,out parsed,out error),"Oversized source text is rejected");
            Check(LabTrajectoryParser.TryParse(string.Join("\n",Enumerable.Repeat("WAIT 0",256)),Vector3.zero,out parsed,out error)&&parsed.Count==256,"Exactly 256 steps are accepted");
            Check(!LabTrajectoryParser.TryParse(string.Join("\n",Enumerable.Repeat("WAIT 0",257)),Vector3.zero,out parsed,out error),"A 257th step is rejected");

            var app=Object.FindObjectOfType<LabTrainingApp>();
            var stations=Object.FindObjectsOfType<LabRobotStation>().OrderBy(s=>s.stationIndex).ToArray();
            var station=stations.FirstOrDefault();
            if(!app||!station)throw new InvalidOperationException("The teaching scene is required.");
            if(Object.FindObjectsOfType<LabTrajectoryProgram>().Any(p=>p.IsExecuting))throw new InvalidOperationException("Stop the user's running program before this isolated regression.");
            bool appEnabled=app.enabled;
            var host=new GameObject("__TrajectoryProgramValidation");
            var program=host.AddComponent<LabTrajectoryProgram>();
            string savedPath=null;
            try
            {
                app.ClosePanel();app.enabled=false;
                station.BeginOperation();station.SetMode(0);station.ResetExercise();program.Bind(station);
                Check(program.Compile(program.ExampleText()),"The station's square example compiles");
                string original=program.ExportText();int originalCount=program.Count;
                Check(!program.Compile("SPEED 60\nMOVE 999999 0 0")&&program.ExportText()==original&&program.Count==originalCount,
                    "Compile is transactional: an out-of-workspace line preserves the previous program");
                Check(!program.Compile("MOVE 1 2")&&program.ExportText()==original,"Syntax failure also preserves the previous program");
                Check(program.Compile(original)&&program.ExportText()==original,"Per-point speed and pen options survive text export/recompile");
                Check(program.Compile(program.ExampleText(true)),"The triangle example is legal for the current exercise scale");
                Check(program.Compile(original),"Square program restored for live execution");
                Check(!program.Save("../escape")&&!program.Save("..\\escape")&&!program.Save("C:\\escape"),"Program names cannot escape the Programs directory");
                string name="Validation_"+Guid.NewGuid().ToString("N").Substring(0,12);
                Check(program.Save(name),"JSON saved in persistent Programs directory: "+program.LastFilePath);
                savedPath=program.LastFilePath;
                Check(program.Compile("WAIT 0.1")&&program.Load(name)&&program.ExportText()==original,"Persistent JSON roundtrip preserves trajectory, speed and pen states");
                File.WriteAllText(savedPath,"{\"version\":999,\"steps\":[]}");
                Check(!program.Load(name)&&program.ExportText()==original,"Invalid JSON version cannot replace the current program");
                Check(program.Save(name),"Valid JSON replaces only the chosen program file");

                double until;
                Check(stations.Length==3,"All three mechanical arms are available for actual program execution");
                foreach(var next in stations)
                {
                    station=next;station.BeginOperation();station.SetMode(0);station.ResetExercise();program.Bind(station);
                    Check(program.Compile(program.ExampleText())&&program.Run(),"Station "+station.stationIndex+" live square program starts");
                    float maxFollowingError=0;
                    until=EditorApplication.timeSinceStartup+30;
                    while(program.IsExecuting&&EditorApplication.timeSinceStartup<until)
                    {
                        maxFollowingError=Mathf.Max(maxFollowingError,station.PositionError);yield return 0;
                    }
                    Check(program.State==LabTrajectoryState.Completed,"Station "+station.stationIndex+" square completes through MoveTool: "+program.StatusText);
                    var strokes=station.GetComponentsInChildren<LineRenderer>(true).Where(l=>l.name=="DrawingStroke").ToArray();
                    int vertices=strokes.Sum(l=>l.positionCount);float ink=0;
                    foreach(var line in strokes)for(int i=1;i<line.positionCount;i++)ink+=Vector3.Distance(line.GetPosition(i-1),line.GetPosition(i));
                    Check(vertices>20&&ink>.1f,"Station "+station.stationIndex+" real end-effector drawing vertices="+vertices+", ink="+ink.ToString("F5")
                        +" m, largest following error="+maxFollowingError.ToString("F6")+" m (simulation units)");
                    Capture(station);Check(!station.PenDown,"Station "+station.stationIndex+" completion lifts the pen");station.EndOperation();
                }
                station=stations[0];station.BeginOperation();station.SetMode(0);station.ResetExercise();program.Bind(station);
                float y=(station.drawingHeight-station.exerciseCenter.y)*1000;
                string target1="MOVE 15 "+F(y)+" 0 SPEED 80 PEN UP\nMOVE -15 "+F(y)+" 0 SPEED 80 PEN UP";
                Check(program.Compile(target1)&&program.Step(),"Single-step starts from the first point");
                until=EditorApplication.timeSinceStartup+8;
                while(program.State==LabTrajectoryState.Running&&EditorApplication.timeSinceStartup<until)yield return 0;
                Check(program.IsPaused&&program.IsExecuting&&program.CurrentStepIndex==1,"Single MOVE reaches its point before pausing and retains exclusive control");
                Vector3 paused=station.toolTarget.localPosition,pausedActual=station.ActualToolPosition;
                int heldFrames=Time.frameCount+12;while(Time.frameCount<heldFrames)yield return 0;
                Check(Vector3.Distance(paused,station.toolTarget.localPosition)<.00001f,"Pause holds the motion target across real frames");
                Check(Vector3.Distance(pausedActual,station.ActualToolPosition)<.0025f,"Paused drawing tool holds its actual position within the drawing arrival tolerance");
                Check(!program.RecordCurrent(false,50),"Program edits are rejected while paused control is reserved");
                Check(program.Resume(),"Resume continues remaining steps");
                heldFrames=Time.frameCount+3;while(Time.frameCount<heldFrames)yield return 0;
                station.SetEmergencyStop(true);
                heldFrames=Time.frameCount+3;while(Time.frameCount<heldFrames)yield return 0;
                Check(program.IsPaused,"Emergency stop automatically pauses the program");
                Check(!program.Resume()&&program.IsPaused,"Program cannot resume until emergency stop is cleared");
                station.SetEmergencyStop(false);Check(program.Resume(),"Clearing emergency stop allows explicit resume");
                until=EditorApplication.timeSinceStartup+8;
                while(program.IsExecuting&&EditorApplication.timeSinceStartup<until)yield return 0;
                Check(program.State==LabTrajectoryState.Completed,"Resumed program completes normally");

                program.Stop();int retained=program.Count;program.Reset();
                Check(program.Count==retained&&program.State==LabTrajectoryState.Ready,"Stop/reset retain the user's program");
                Check(program.RecordCurrent(false,45),"Current manual target can be recorded as an independent taught point");
                var edited=program.Steps[program.Count-1].Copy();edited.speedPercent=35;
                Check(program.UpdateStep(program.Count-1,edited)&&program.MoveStep(program.Count-1,0)&&program.DeleteStep(0),"Taught steps can be edited, reordered and removed");

                Check(program.Compile("WAIT 2")&&program.Run(),"Exit-stop test starts");
                station.EndOperation();heldFrames=Time.frameCount+3;while(Time.frameCount<heldFrames)yield return 0;
                Check(!program.IsExecuting&&program.Count==1,"Leaving the station stops execution and retains the program");
                station.BeginOperation();station.SetMode(0);Check(program.Run(),"Mode-stop test starts");
                station.SetMode(1);heldFrames=Time.frameCount+3;while(Time.frameCount<heldFrames)yield return 0;
                Check(!program.IsExecuting,"Changing training mode stops execution");
                program.Stop();
                Check(program.Compile(program.ExampleText()),"Ring centreline example compiles within 256 steps");
                station.ResetExercise();
                Check(program.Run(),"Station 0 ring centreline example starts through the real program Update -> MoveTool adapter");
                float ringStarted=Time.time,ringMaxFollowingError=0;
                var gripSamples=new RingGripSamples();
                bool ringPauseChecked=false;
                until=EditorApplication.timeSinceStartup+180;
                while(program.IsExecuting&&EditorApplication.timeSinceStartup<until)
                {
                    gripSamples.Observe(station);
                    ringMaxFollowingError=Mathf.Max(ringMaxFollowingError,station.PositionError);
                    if(!ringPauseChecked&&station.Progress>.12f&&program.State==LabTrajectoryState.Running)
                    {
                        program.Pause();
                        Check(program.IsPaused&&program.IsExecuting,"Ring pause retains the program's exclusive control");
                        Vector3 circleAtPause=station.ActualToolPosition,targetAtPause=station.toolTarget.position;
                        float maximumCircleDrift=0;
                        heldFrames=Time.frameCount+8;
                        while(Time.frameCount<heldFrames&&EditorApplication.timeSinceStartup<until)
                        {
                            gripSamples.Observe(station);
                            maximumCircleDrift=Mathf.Max(maximumCircleDrift,Vector3.Distance(circleAtPause,station.ActualToolPosition));
                            yield return 0;
                        }
                        Check(Vector3.Distance(targetAtPause,station.toolTarget.position)<.00001f,"Ring pause holds the centre target across real frames");
                        Check(maximumCircleDrift<.0004f,"Ring pause holds the actual circle centre; maximum drift="+maximumCircleDrift.ToString("F6")+" m");
                        Check(program.Resume(),"Ring centreline program resumes after the actual-centre pause check");
                        ringPauseChecked=true;
                    }
                    yield return 0;
                }
                gripSamples.Observe(station);
                report.Add("RING_PROGRAM state="+program.State+" progress="+station.Progress.ToString("F6")+" contacts="+station.Contacts
                    +" simulatedSeconds="+(Time.time-ringStarted).ToString("F3")+" maxFollowingError="+ringMaxFollowingError.ToString("F6")
                    +" m; status="+program.StatusText);
                Check(program.State==LabTrajectoryState.Completed,"Station 0 real ring centreline program completes within the 180-second wall-clock limit");
                Check(ringPauseChecked,"The live ring program exercised pause and resume while traversing the guide");
                Check(station.Progress>=.99f,"The program carries the ring through at least 99% of the actual steel guide; progress="+station.Progress.ToString("F6"));
                Check(station.Contacts==0,"Following every sampled wire centreline point introduces no rim contacts; contacts="+station.Contacts);
                program.Stop();station.ResetExercise();
                Vector3 tangent=(station.wirePoints[1]-station.wirePoints[0]).normalized;
                Vector3 rejected=station.wirePoints[0]-tangent*.02f;
                Vector3 mm=(rejected-station.exerciseCenter)*1000;
                Check(program.Compile("MOVE "+F(mm.x)+" "+F(mm.y)+" "+F(mm.z)+" SPEED 60 PEN UP")&&program.Run(),"A workspace-valid move toward the ring's endpoint barrier starts");
                Vector3 initial=station.toolTarget.localPosition,initialActual=station.ActualToolPosition;
                float minimumEndpointProjection=float.PositiveInfinity;
                until=EditorApplication.timeSinceStartup+6;
                while(program.IsExecuting&&EditorApplication.timeSinceStartup<until)
                {
                    gripSamples.Observe(station);
                    Vector3 actualLocal=station.transform.InverseTransformPoint(station.ActualToolPosition);
                    minimumEndpointProjection=Mathf.Min(minimumEndpointProjection,Vector3.Dot(actualLocal-station.wirePoints[0],tangent));
                    yield return 0;
                }
                gripSamples.Observe(station);
                minimumEndpointProjection=Mathf.Min(minimumEndpointProjection,Vector3.Dot(station.transform.InverseTransformPoint(station.ActualToolPosition)-station.wirePoints[0],tangent));
                Check(program.State==LabTrajectoryState.Faulted&&program.LastError.Contains("1")&&program.LastError.Contains("边界"),
                    "Blocked ring move terminates with its exact step/line instead of looping: "+program.LastError);
                Check(Vector3.Distance(initial,station.toolTarget.localPosition)<.002f,"The blocked program cannot drive the ring through its endpoint");
                Check(Vector3.Distance(initialActual,station.ActualToolPosition)<.002f&&minimumEndpointProjection>=-.0002f,
                    "The actual circle centre remains inside the start endpoint tolerance throughout the blocked program; minimum projection="+minimumEndpointProjection.ToString("F6")+" m");
                gripSamples.AssertValid(station);
                report.Add("PASS: All bounded parser, persistence and actual-motion program checks completed.");
            }
            finally
            {
                program.Stop();station.SetEmergencyStop(false);station.SetMode(0);station.ResetExercise();station.EndOperation();
                app.ClosePanel();app.enabled=appEnabled;
                if(savedPath!=null&&File.Exists(savedPath))File.Delete(savedPath);
                Object.DestroyImmediate(host);
            }
        }
        sealed class RingGripSamples
        {
            int lastFrame=-1,samples;
            bool finite=true;
            float minimum=float.PositiveInfinity,maximum=0;
            public void Observe(LabRobotStation station)
            {
                if(lastFrame==Time.frameCount)return;
                lastFrame=Time.frameCount;samples++;
                float distance=Vector3.Distance(station.ActualToolPosition,station.RingGripPosition);
                finite&=!float.IsNaN(distance)&&!float.IsInfinity(distance);
                minimum=Mathf.Min(minimum,distance);maximum=Mathf.Max(maximum,distance);
            }
            public void AssertValid(LabRobotStation station)
            {
                report.Add("RING_GRIP samples="+samples+" circleToGripMin="+minimum.ToString("F6")
                    +" circleToGripMax="+maximum.ToString("F6")+" radius="+station.ringRadius.ToString("F6")+" m");
                Check(samples>10&&finite&&minimum>=station.ringRadius*.95f&&maximum<=station.ringRadius*1.05f,
                    "The actual ring centre remains one radius from the rim-gripping TCP throughout execution, pause and endpoint blocking");
            }
        }
        static string F(float number)=>number.ToString("0.#####",System.Globalization.CultureInfo.InvariantCulture);
        static void Check(bool condition,string message){report.Add((condition?"PASS: ":"FAIL: ")+message);if(!condition)throw new InvalidOperationException(message);}
        static void Capture(LabRobotStation station)
        {
            var host=new GameObject("__TrajectoryDrawingCamera"){hideFlags=HideFlags.HideAndDontSave};
            RenderTexture rt=null;Texture2D texture=null;var previous=RenderTexture.active;
            try
            {
                var camera=host.AddComponent<Camera>();camera.enabled=false;camera.fieldOfView=38;camera.nearClipPlane=.03f;
                Vector3 target=station.transform.TransformPoint(station.exerciseCenter);
                camera.transform.position=target+new Vector3(1.05f,.9f,-.7f);camera.transform.LookAt(target);
                rt=new RenderTexture(1600,1000,24){antiAliasing=4};camera.targetTexture=rt;camera.Render();RenderTexture.active=rt;
                texture=new Texture2D(1600,1000,TextureFormat.RGB24,false);texture.ReadPixels(new Rect(0,0,1600,1000),0,0);texture.Apply();
                Directory.CreateDirectory("Documentation/Screenshots");
                byte[] png=texture.EncodeToPNG();
                File.WriteAllBytes("Documentation/Screenshots/TrajectoryDrawing_Station"+(station.stationIndex+1).ToString("00")+".png",png);
                if(station.stationIndex==0)File.WriteAllBytes("Documentation/Screenshots/TrajectoryDrawing.png",png);
            }
            finally{RenderTexture.active=previous;if(host)host.GetComponent<Camera>().targetTexture=null;if(texture)Object.DestroyImmediate(texture);if(rt){rt.Release();Object.DestroyImmediate(rt);}Object.DestroyImmediate(host);}
        }
    }
}
